// Minimal service worker - required for "installable" PWA status.
// Keeps things simple: doesn't aggressively cache game files, since this is
// a live multiplayer game and stale cached JS could break connections.
const CACHE_NAME = "dehla-coat-shell-v1";

self.addEventListener("install", (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) return caches.delete(key);
        })
      )
    )
  );
  self.clients.claim();
});

// Network-first: always try to get the freshest game files.
// Falls back to cache only if the network genuinely fails (offline).
self.addEventListener("fetch", (event) => {
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const clone = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
